CREATE TYPE episode_event_status AS ENUM ('current', 'deletion_pending', 'deleted');
CREATE TYPE event_draft_intent AS ENUM ('create', 'update');
CREATE TYPE event_draft_mode AS ENUM ('autosave', 'manual');

